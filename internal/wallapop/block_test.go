package wallapop

import (
	"context"
	"fmt"
	"net/http"
	"net/http/httptest"
	"testing"
)

// Page fetches get no browser user agent retry, so CloudFront's 403 to the
// honest agent must not pause renewals; once the browser agent was already
// refused, it is a real block.
func TestPageBlockPausesOnlyAfterTheBrowserAgentFailed(t *testing.T) {
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.WriteHeader(http.StatusForbidden)
		fmt.Fprint(w, "<html><body>The request could not be satisfied. Generated by cloudfront (CloudFront)</body></html>")
	}))
	defer srv.Close()
	c := New("test")
	c.WebBase = srv.URL
	blocks := 0
	c.OnBlock = func(context.Context) { blocks++ }
	if err := c.nextData(context.Background(), "/item/x", nil); err == nil || blocks != 0 {
		t.Fatalf("honest agent: err %v, %d blocks", err, blocks)
	}
	c.setBrowserUA()
	if err := c.nextData(context.Background(), "/item/x", nil); err == nil || blocks != 1 {
		t.Fatalf("browser agent: err %v, %d blocks", err, blocks)
	}
	if isBotBlock(http.StatusForbidden, nil) || isBotBlock(http.StatusForbidden, []byte(`{"code":1}`)) || !isBotBlock(http.StatusTooManyRequests, nil) {
		t.Fatal("a bare or JSON 403 is Wallapop's own answer, a 429 is always a block")
	}
}
