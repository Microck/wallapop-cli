func (s *Server) search(w http.ResponseWriter, r *http.Request) {
	s.mu.Lock()
	defer s.mu.Unlock()
	start := 0
	if r.URL.Query().Get("next_page") == "page2" {
		start = 40
	}
	var items []map[string]any
	for i := start; i < len(s.SearchOrder) && i < start+40; i++ {
		it := s.Items[s.SearchOrder[i]]
		if it.Removed {
			continue
		}
		items = append(items, s.searchItemJSON(it))
	}
	if items == nil {
		items = []map[string]any{}
	}
	next := ""
	if start == 0 && len(s.SearchOrder) > 40 {
		next = "page2"
	}
	w.Header().Set("x-wallapop-search-id", "search-id-1")
	writeJSON(w, 200, map[string]any{
		"data": map[string]any{"section": map[string]any{"type": "organic_search_results", "payload": map[string]any{"items": items}}},
		"meta": map[string]any{"next_page": next, "next_section_type": ""},
	})
}

func (s *Server) filters(w http.ResponseWriter, r *http.Request) {
	list := func(id, title, key string, opts ...string) map[string]any {
		var options []map[string]any
		for _, o := range opts {
			options = append(options, map[string]any{"id": o, "title": o, "is_selected": false})
		}
		return map[string]any{"id": id, "title": title, "type": "list",
			"search_params": map[string]any{"list_param": map[string]any{"param_key": key}},
			"type_data":     map[string]any{"source_data": map[string]any{"options_data": map[string]any{"options": options}}}}
	}
	filters := []map[string]any{
		{"id": "price", "title": "Price", "type": "slider", "search_params": map[string]any{"min_param": map[string]any{"param_key": "min_sale_price"}, "max_param": map[string]any{"param_key": "max_sale_price"}}},
		list("condition", "Condition", "condition", "new", "good"),
	}
	if r.URL.Query().Get("category_id") == "100" {
		filters = append(filters, list("brand", "Brand", "brand", "Toyota", "Seat"),
			map[string]any{"id": "km_cars", "title": "Km", "type": "slider", "search_params": map[string]any{"min_param": map[string]any{"param_key": "min_km"}, "max_param": map[string]any{"param_key": "max_km"}}})
	}
	writeJSON(w, 200, map[string]any{"selected_filters": []any{}, "filter_sections": []map[string]any{{"filters": filters}}})
}

