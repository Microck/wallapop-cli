// Package fakewallapop is a real HTTP server that answers like Wallapop's API
// host, web host and PubNub, with the response shapes recorded on 2026-09-14
// and enough mutable state that writes are observable. Tests point the three
// WALLAPOP_*_BASE_URL variables at one instance.
package fakewallapop

import (
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"net/http/httptest"
	"net/url"
	"strconv"
	"strings"
	"sync"
	"time"
)

const (
	ValidCookie   = "eyJhbGciOiJkaXIiLCJlbmMiOiJBMjU2R0NNIn0..valid-session.cookie-value-that-is-long-enough-to-look-like-a-jwe-0123456789abcdef"
	RotatedCookie = "eyJhbGciOiJkaXIiLCJlbmMiOiJBMjU2R0NNIn0..rotated-session.cookie-value-that-is-long-enough-to-look-like-a-jwe-0123456789abcdef"
	UserHash      = "kmznw7w2k7zn"
	OtherHash     = "p8j35kmwr7z9"
	// SavedSearchID is the one saved search the fake account owns.
	SavedSearchID = "a456aa5a-3d86-49bd-a8ca-504f410b127c"
)

// Item is the fake's canonical listing; every endpoint renders from it.
type Item struct {
	Hash        string
	Slug        string
	Title       string
	Description string
	Price       float64
	Condition   string
	Images      int
	Seller      string
	Reserved    bool
	Sold        bool
	Removed     bool // page 404s, API detail 404s
	Modified    time.Time
}

type Conversation struct {
	Hash     string
	Item     string
	Other    string
	Channel  string
	Unread   int
	Archived bool
	Messages []Message
}

type Message struct {
	ID        string
	FromSelf  bool
	Text      string
	At        time.Time
	TimeToken string
}

// Published is one PubNub publish the fake received.
type Published struct {
	Channel string
	Message map[string]any
	Meta    map[string]any
	UUID    string
}

type Request struct {
	Method string
	Path   string
	Query  url.Values
	UA     string
	Auth   string
}

type Server struct {
	*httptest.Server
	mu sync.Mutex

	Items         map[string]*Item
	SearchOrder   []string // hashes returned by search, in order; 40 per page
	Favorites     map[string]bool
	Conversations map[string]*Conversation
	Published     []Published
	Actions       []map[string]any // message actions (seen/received)
	Requests      []Request

	// Failure knobs.
	BlockNextAPI  bool // next api.wallapop.com request gets a CloudFront 403
	MintEmpty     bool // /api/auth/session answers {} (invalid session)
	MalformedItem bool // /api/v3/items/{hash} answers non-JSON
	CreateCalls   int
	Uploads       map[string]int // pictures received per upload id
	WebhookStatus int            // status for POST /hook (0 = 200)
	Hooks         []json.RawMessage
}

func New() *Server {
	s := &Server{
		Items:         map[string]*Item{},
		Favorites:     map[string]bool{},
		Conversations: map[string]*Conversation{},
	}
	s.Server = httptest.NewServer(http.HandlerFunc(s.handle))
	return s
}

// Env returns the variables that point the CLI at this fake.
func (s *Server) Env() map[string]string {
	return map[string]string{
		"WALLAPOP_API_BASE_URL":    s.URL,
		"WALLAPOP_WEB_BASE_URL":    s.URL,
		"WALLAPOP_PUBNUB_BASE_URL": s.URL,
	}
}

func (s *Server) AddItem(it Item) *Item {
	s.mu.Lock()
	defer s.mu.Unlock()
	if it.Slug == "" {
		it.Slug = strings.ToLower(strings.ReplaceAll(it.Title, " ", "-")) + "-1301645280"
	}
	if it.Seller == "" {
		it.Seller = OtherHash
	}
	if it.Modified.IsZero() {
		it.Modified = time.Date(2026, 9, 14, 10, 0, 0, 0, time.UTC)
	}
	cp := it
	s.Items[it.Hash] = &cp
	s.SearchOrder = append(s.SearchOrder, it.Hash)
	return &cp
}

func (s *Server) AddConversation(c Conversation) *Conversation {
	s.mu.Lock()
	defer s.mu.Unlock()
	if c.Channel == "" {
		c.Channel = "chat." + c.Other + "." + c.Item + "." + UserHash
	}
	if c.Other == "" {
		c.Other = OtherHash
	}
	cp := c
	s.Conversations[c.Hash] = &cp
	return &cp
}

// RequestsTo returns the recorded requests with exactly this path.
func (s *Server) RequestsTo(path string) []Request {
	s.mu.Lock()
	defer s.mu.Unlock()
	var out []Request
	for _, r := range s.Requests {
		if r.Path == path {
			out = append(out, r)
		}
	}
	return out
}

// RequestsUnder returns the recorded requests whose path starts with prefix.
func (s *Server) RequestsUnder(prefix string) []Request {
	s.mu.Lock()
	defer s.mu.Unlock()
	var out []Request
	for _, r := range s.Requests {
		if strings.HasPrefix(r.Path, prefix) {
			out = append(out, r)
		}
	}
	return out
}

func (s *Server) handle(w http.ResponseWriter, r *http.Request) {
	s.mu.Lock()
	s.Requests = append(s.Requests, Request{Method: r.Method, Path: r.URL.Path, Query: r.URL.Query(), UA: r.UserAgent(), Auth: r.Header.Get("Authorization")})
	block := s.BlockNextAPI && strings.HasPrefix(r.URL.Path, "/api/v3/")
	if block {
		s.BlockNextAPI = false
	}
	s.mu.Unlock()
	if block {
		w.WriteHeader(http.StatusForbidden)
		fmt.Fprint(w, "<html><body><h1>403 ERROR</h1><p>The request could not be satisfied.</p>Generated by cloudfront (CloudFront)</body></html>")
		return
	}
	p := r.URL.Path
	switch {
	case p == "/api/auth/session":
		s.session(w, r)
	case p == "/api/v3/search":
		s.search(w, r)
	case p == "/api/v3/search/filters/regular-filters":
		s.filters(w, r)
	case strings.HasPrefix(p, "/api/v3/searchalerts/savedsearch/"):
		s.savedSearches(w, r)
	case p == "/api/v3/categories":
		s.categories(w, r)
	case p == "/api/v3/users/me":
		if !s.authed(w, r) {
			return
		}
		writeJSON(w, 200, s.rawUser(UserHash, "Test User", "test-user-1"))
	case strings.HasPrefix(p, "/api/v3/users/"):
		s.users(w, r)
	case p == "/api/v3/user/items", p == "/api/v3/user/items/sold", p == "/api/v3/user/items/favorited":
		if !s.authed(w, r) {
			return
		}
		s.mu.Lock()
		var data []map[string]any
		for _, h := range s.SearchOrder {
			it := s.Items[h]
			if p == "/api/v3/user/items/favorited" && s.Favorites[h] || p != "/api/v3/user/items/favorited" && it.Seller == UserHash && it.Sold == strings.HasSuffix(p, "/sold") {
				data = append(data, s.userItemJSON(it))
			}
		}
		s.mu.Unlock()
		if data == nil {
			data = []map[string]any{}
		}
		writeJSON(w, 200, map[string]any{"data": data, "meta": map[string]any{}})
	case p == "/api/v3/items" && r.Method == http.MethodPost:
		s.createItem(w, r)
	case p == "/api/v3/items/upload/components":
		if !s.authed(w, r) {
			return
		}
		writeJSON(w, 200, map[string]any{"components": []any{}})
	case strings.HasPrefix(p, "/api/v3/upload/") && strings.HasSuffix(p, "/pictures"):
		if !s.authed(w, r) {
			return
		}
		id := strings.TrimSuffix(strings.TrimPrefix(p, "/api/v3/upload/"), "/pictures")
		s.mu.Lock()
		if s.Uploads == nil {
			s.Uploads = map[string]int{}
		}
		s.Uploads[id]++
		s.mu.Unlock()
		w.WriteHeader(204)
	case strings.HasPrefix(p, "/api/v3/items/"):
		s.items(w, r)
	case strings.HasPrefix(p, "/item/"):
		s.itemPage(w, r)
	case strings.HasPrefix(p, "/user/"):
		s.userPage(w, r)
	case p == "/bff/messaging/inbox" || p == "/bff/messaging/archived":
		s.inbox(w, r, p == "/bff/messaging/archived")
	case strings.HasPrefix(p, "/bff/messaging/conversation/"):
		s.conversation(w, r)
	case strings.HasPrefix(p, "/api/v3/instant-messaging/archive/conversation/"):
		if !s.authed(w, r) {
			return
		}
		writeJSON(w, 200, map[string]any{"messages": []any{}, "next_from": ""})
	case p == "/api/v3/instant-messaging/token":
		if !s.authed(w, r) {
			return
		}
		writeJSON(w, 201, map[string]any{"token": "pam-token", "channels": []string{"inbox." + UserHash, "signals." + UserHash}})
	case p == "/api/v3/instant-messaging/conversation":
		s.createConversation(w, r)
	case p == "/api/v3/instant-messaging/conversations/archive", p == "/api/v3/instant-messaging/conversations/unarchive":
		s.archive(w, r, strings.HasSuffix(p, "/archive"))
	case p == "/api/v3/instant-messaging/messages/unread":
		writeJSON(w, 200, map[string]any{"unread_counter": 0})
	case strings.HasPrefix(p, "/publish/"):
		s.publish(w, r)
	case strings.HasPrefix(p, "/v2/subscribe/"):
		s.subscribe(w, r)
	case strings.HasPrefix(p, "/v1/message-actions/"):
		s.messageAction(w, r)
	case p == "/hook" || strings.HasPrefix(p, "/ntfy/"):
		s.hook(w, r)
	default:
		writeJSON(w, 404, map[string]any{"code": 0, "message": "not found", "type": 0})
	}
}

// owned mirrors Wallapop's answer to an authenticated write on someone else's
// item, recorded 2026-09-15: a bare 401 for reserve and delete, 403 for sold,
// no body. Unauthenticated foreign writes were not exercised, so authed runs
// first by assumption.
func (s *Server) owned(w http.ResponseWriter, it *Item, status int) bool {
	if it.Seller == UserHash {
		return true
	}
	w.WriteHeader(status)
	return false
}

func writeJSON(w http.ResponseWriter, status int, v any) {
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(status)
	_ = json.NewEncoder(w).Encode(v)
}

func (s *Server) authed(w http.ResponseWriter, r *http.Request) bool {
	if r.Header.Get("Authorization") != "Bearer access-token" {
		writeJSON(w, 401, map[string]any{"code": 401, "message": "unauthorized"})
		return false
	}
	return true
}

func (s *Server) session(w http.ResponseWriter, r *http.Request) {
	s.mu.Lock()
	empty := s.MintEmpty
	s.mu.Unlock()
	cookie := ""
	for _, c := range r.Cookies() {
		if c.Name == "__Secure-next-auth.session-token" {
			cookie = c.Value
		}
	}
	if empty || (cookie != ValidCookie && cookie != RotatedCookie) {
		writeJSON(w, 200, map[string]any{})
		return
	}
	// The real route re-issues the cookie with a fresh 30-day Expires on every mint.
	http.SetCookie(w, &http.Cookie{Name: "__Secure-next-auth.session-token", Value: RotatedCookie, Path: "/", HttpOnly: true, Secure: true, Expires: time.Now().Add(30 * 24 * time.Hour).Truncate(time.Second)})
	// Not a real JWT: the CLI falls back to a four-minute cache when exp is unreadable.
	writeJSON(w, 200, map[string]any{"token": "access-token", "idToken": "id", "expires": time.Now().Add(30 * 24 * time.Hour).Format(time.RFC3339), "user": map[string]any{}})
}

